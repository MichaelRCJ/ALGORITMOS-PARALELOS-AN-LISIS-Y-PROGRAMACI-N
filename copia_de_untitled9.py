def safe_name(text, i):
    base = re.sub(r"[^A-Za-z0-9._-]+", "_", norm(text))[:90].strip("_")
    return f"{i:03d}_{base or 'articulo'}.pdf"

def download_pdfs(_=None):
    with salida_descarga:
        clear_output()
        try:
            df = selected_df()
        except Exception as e:
            print("⚠️", e); return
        zip_path = Path("articulos_acceso_abierto.zip")
        ok, failed = 0, []
        with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
            for i, (_, row) in enumerate(df.iterrows(), 1):
                url = str(row.get("pdf_oa") or "").strip()
                if not url:
                    failed.append((row.get("titulo", ""), "sin PDF abierto")); continue
                try:
                    r = SESSION.get(url, timeout=45, allow_redirects=True)
                    ctype = (r.headers.get("content-type") or "").lower()
                    if r.status_code != 200 or ("pdf" not in ctype and not r.content.startswith(b"%PDF")):
                        raise ValueError(f"respuesta no PDF ({r.status_code}, {ctype[:40]})")
                    zf.writestr(safe_name(row.get("titulo"), i), r.content)
                    ok += 1
                except Exception as e:
                    failed.append((row.get("titulo", ""), str(e)))
        print(f"✅ {ok} PDF guardados. {len(failed)} no disponibles para descarga directa.")
        if failed:
            display(pd.DataFrame(failed, columns=["articulo", "motivo"]).head(30))
        if ok:
            send_file(zip_path)
        else:
            zip_path.unlink(missing_ok=True)

